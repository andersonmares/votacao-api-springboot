CREATE TABLE IF NOT EXISTS pauta (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     titulo VARCHAR(255) NOT NULL,
    descricao TEXT,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

CREATE TABLE IF NOT EXISTS voto (
                                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    cpf VARCHAR(14) NOT NULL,
    associado_id BIGINT NOT NULL,
    voto BOOLEAN NOT NULL,          -- true = SIM, false = NAO (se quiser manter BOOLEAN)
    pauta_id BIGINT NOT NULL REFERENCES pauta(id),
    CONSTRAINT uk_voto_pauta_associado UNIQUE (pauta_id, associado_id)
    );

CREATE INDEX IF NOT EXISTS idx_voto_associado   ON voto(associado_id);
CREATE INDEX IF NOT EXISTS idx_voto_cpf         ON voto(cpf);
CREATE INDEX IF NOT EXISTS idx_voto_pauta_voto  ON voto(pauta_id, voto);